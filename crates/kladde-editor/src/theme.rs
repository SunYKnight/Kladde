    pub fn token_color(&self, k: TokenKind) -> Color32 {
        match k {
            TokenKind::Plain => self.fg,
            TokenKind::Keyword => self.keyword,
            TokenKind::Type => self.type_name,
            TokenKind::Function => self.function,
            TokenKind::String => self.string,
            TokenKind::Number => self.number,
            TokenKind::Comment => self.comment,
            TokenKind::Preprocessor => self.preprocessor,
            TokenKind::Operator => self.operator,
            TokenKind::Tag => self.tag,
            TokenKind::Attribute => self.attribute,
            TokenKind::Heading => self.heading,
            TokenKind::Emphasis => self.emphasis,
            TokenKind::Link => self.link,
            TokenKind::Code => self.code,
            TokenKind::Variable => self.variable,
            TokenKind::Constant => self.constant,
            TokenKind::Escape => self.escape,
            TokenKind::CsvColumn(i) => self.csv_columns[usize::from(i % RAINBOW_COLUMNS)],
        }
    }
